//
//  CJKCharacterCosts.swift
//  LDACore
//
//  How common each Hangul syllable and each Chinese character is, for
//  TextEncodingDetector to weigh a CP949 reading of a file against a GB18030
//  or Big5 reading of the same bytes (review 2026-11-11, F4).
//
//  A cost is a whole number of bits: the negative base-2 logarithm of the
//  character's share of running text, so a common character costs little and
//  a rare one a lot. A reading of the right encoding is made of common
//  characters; the same bytes read in the wrong one land on characters
//  spread evenly over the code table, most of them rare. Only the
//  1446 syllables and 3500 characters below their unknown cost are listed;
//  any other costs the unknown cost.
//
//  Counted, not copied: the Hangul counts come from the Korean interface text
//  of macOS plus a list of legal terms and given names; the hanzi counts from
//  the word frequencies of the jieba word list (MIT licence), each Simplified
//  character also counted under its Traditional form, plus the Chinese
//  interface text of macOS at a smaller weight. No text from either source is
//  reproduced here.
//
//  House rules: all comments and strings in English. No em-dash and no
//  en-dash-as-separator anywhere.
//

enum CJKCharacterCosts {

    /// The cost of a Hangul syllable not listed in hangulBands, and of a
    /// Hanja in a Korean reading.
    static let unknownHangulCost = 24

    /// The cost of a Chinese character not listed in hanziBands.
    static let unknownHanziCost = 20

    /// The cost of a Hangul syllable in bits.
    static func hangulCost(_ scalar: Unicode.Scalar) -> Int {
        hangul[scalar] ?? unknownHangulCost
    }

    /// The cost of a Chinese character in bits.
    static func hanziCost(_ scalar: Unicode.Scalar) -> Int {
        hanzi[scalar] ?? unknownHanziCost
    }

    private static let hangul = table(hangulBands)
    private static let hanzi = table(hanziBands)

    private static func table(_ bands: [(cost: Int, characters: String)]) -> [Unicode.Scalar: Int] {
        var costs: [Unicode.Scalar: Int] = [:]
        for band in bands {
            for scalar in band.characters.unicodeScalars where costs[scalar] == nil {
                costs[scalar] = band.cost
            }
        }
        return costs
    }

